using System.Net;
using DevTools.Providers;
using Xunit;

namespace DevTools.Tests;

public sealed class AuditTests
{
    private const string NpmLock = """
        {
          "name": "demo", "lockfileVersion": 3,
          "packages": {
            "": { "name": "demo", "version": "1.0.0" },
            "node_modules/lodash": { "version": "4.17.15" },
            "node_modules/@scope/pkg": { "version": "2.0.1" },
            "node_modules/a/node_modules/lodash": { "version": "3.10.1" },
            "node_modules/local-link": { "resolved": "../local", "link": true },
            "node_modules/no-version": { }
          }
        }
        """;

    private const string CargoLock = """
        # This file is automatically @generated by Cargo.
        version = 3

        [[package]]
        name = "time"
        version = "0.1.43"
        source = "registry+https://github.com/rust-lang/crates.io-index"
        checksum = "abc"

        [[package]]
        name = "my-local-crate"
        version = "0.1.0"

        [[package]]
        name = "serde"
        version = "1.0.200"
        source = "registry+https://github.com/rust-lang/crates.io-index"
        """;

    [Fact]
    public void NpmLockfileGivesEveryResolvedPackageIncludingNestedAndScopedOnes()
    {
        var packages = DependencyReader.ParseNpmLock(NpmLock);
        Assert.Equal(
            [("npm", "@scope/pkg", "2.0.1"), ("npm", "lodash", "3.10.1"), ("npm", "lodash", "4.17.15")],
            packages.OrderBy(p => p.Name, StringComparer.Ordinal).ThenBy(p => p.Version, StringComparer.Ordinal)
                .Select(p => (p.Ecosystem, p.Name, p.Version)));
    }

    [Fact]
    public void NpmLockfileWithoutPackagesMapIsEmptyNotAnError() =>
        Assert.Empty(DependencyReader.ParseNpmLock("""{"lockfileVersion":1,"dependencies":{"a":{"version":"1.0.0"}}}"""));

    [Theory]
    [InlineData("")]
    [InlineData("not json")]
    public void BrokenNpmLockfileThrowsInvalidData(string text) =>
        Assert.Throws<InvalidDataException>(() => DependencyReader.ParseNpmLock(text));

    [Fact]
    public void CargoLockGivesRegistryCratesOnly()
    {
        var packages = DependencyReader.ParseCargoLock(CargoLock);
        Assert.Equal([("crates.io", "serde", "1.0.200"), ("crates.io", "time", "0.1.43")],
            packages.OrderBy(p => p.Name, StringComparer.Ordinal).Select(p => (p.Ecosystem, p.Name, p.Version)));
    }

    [Fact]
    public void ReaderUsesWhicheverLockfilesExist()
    {
        var directory = Path.Combine(Path.GetTempPath(), "devtools-tests", Guid.NewGuid().ToString("N"));
        try
        {
            Directory.CreateDirectory(directory);
            Assert.Empty(DependencyReader.Read(directory).Dependencies);
            File.WriteAllText(Path.Combine(directory, "package-lock.json"), NpmLock);
            File.WriteAllText(Path.Combine(directory, "Cargo.lock"), CargoLock);
            var read = DependencyReader.Read(directory);
            Assert.Equal(5, read.Dependencies.Count);
            Assert.Equal(["Cargo.lock", "package-lock.json"], read.Files.Order(StringComparer.Ordinal));
        }
        finally { if (Directory.Exists(directory)) Directory.Delete(directory, true); }
    }

    // ---- OSV client with a fake handler ----

    private sealed class Fake(Func<HttpRequestMessage, string?, HttpResponseMessage> respond) : HttpMessageHandler
    {
        public List<(string Method, string Url, string? Body)> Calls { get; } = [];

        protected override HttpResponseMessage Send(HttpRequestMessage request, CancellationToken cancellationToken)
        {
            var body = request.Content?.ReadAsStringAsync(cancellationToken).GetAwaiter().GetResult();
            Calls.Add((request.Method.Method, request.RequestUri!.ToString(), body));
            return respond(request, body);
        }

        protected override Task<HttpResponseMessage> SendAsync(HttpRequestMessage request, CancellationToken cancellationToken) =>
            Task.FromResult(Send(request, cancellationToken));
    }

    private static HttpResponseMessage Json(string body, HttpStatusCode status = HttpStatusCode.OK) =>
        new(status) { Content = new StringContent(body, System.Text.Encoding.UTF8, "application/json") };

    private static HttpResponseMessage Route(HttpRequestMessage request, string? body)
    {
        if (request.RequestUri!.AbsolutePath.EndsWith("/v1/querybatch", StringComparison.Ordinal))
            return Json("""{"results":[{"vulns":[{"id":"GHSA-1","modified":"x"},{"id":"RUSTSEC-9","modified":"x"}]},{},{"vulns":[{"id":"RUSTSEC-9","modified":"x"}]}]}""");
        return request.RequestUri.AbsolutePath.EndsWith("GHSA-1", StringComparison.Ordinal)
            ? Json("""{"id":"GHSA-1","summary":"ReDoS in lodash","database_specific":{"severity":"MODERATE"}}""")
            : Json("""{"id":"RUSTSEC-9","summary":"Potential segfault"}""");
    }

    private static readonly Dependency[] Three =
    [
        new("npm", "lodash", "4.17.15"), new("npm", "lodash", "4.17.21"), new("crates.io", "time", "0.1.43")
    ];

    [Fact]
    public void BatchRequestSendsOnlyNameEcosystemAndVersionAndMapsResultsByPosition()
    {
        var handler = new Fake(Route);
        var findings = new OsvClient(handler).Audit(Three);

        var batch = Assert.Single(handler.Calls, call => call.Url.EndsWith("/v1/querybatch", StringComparison.Ordinal));
        Assert.Equal("POST", batch.Method);
        Assert.Equal("https://api.osv.dev/v1/querybatch", batch.Url);
        Assert.Contains("\"ecosystem\":\"npm\"", batch.Body);
        Assert.Contains("\"name\":\"lodash\"", batch.Body);
        Assert.Contains("\"version\":\"4.17.15\"", batch.Body);

        Assert.Equal(2, findings.Vulnerable.Count);
        Assert.Equal(["GHSA-1", "RUSTSEC-9"], findings.Vulnerable.Single(f => f.Dependency.Version == "4.17.15").Vulnerabilities.Select(v => v.Id));
        Assert.Equal("MODERATE", findings.Vulnerable[0].Vulnerabilities[0].Severity);
        Assert.Null(findings.Vulnerable.Single(f => f.Dependency.Name == "time").Vulnerabilities.Single().Severity);
        Assert.Empty(findings.Errors);
    }

    [Fact]
    public void EachDistinctVulnerabilityRecordIsFetchedOnlyOnce()
    {
        var handler = new Fake(Route);
        new OsvClient(handler).Audit(Three);
        Assert.Equal(1, handler.Calls.Count(call => call.Url.EndsWith("/v1/vulns/GHSA-1", StringComparison.Ordinal)));
    }

    [Fact]
    public void LargeInputsAreSplitIntoSeveralBatches()
    {
        var handler = new Fake((request, body) =>
        {
            if (!request.RequestUri!.AbsolutePath.EndsWith("/v1/querybatch", StringComparison.Ordinal)) return Json("{}");
            using var document = System.Text.Json.JsonDocument.Parse(body!);
            var count = document.RootElement.GetProperty("queries").GetArrayLength();
            return Json("{\"results\":[" + string.Join(",", Enumerable.Repeat("{}", count)) + "]}");
        });
        var many = Enumerable.Range(0, OsvClient.BatchSize + 5).Select(i => new Dependency("npm", "p" + i, "1.0.0")).ToList();
        var result = new OsvClient(handler).Audit(many);
        Assert.Equal(2, handler.Calls.Count(call => call.Url.EndsWith("/v1/querybatch", StringComparison.Ordinal)));
        Assert.Empty(result.Vulnerable);
    }

    [Fact]
    public void HttpFailureIsReportedWithStatusAndBodyAndNothingIsClaimedClean()
    {
        var handler = new Fake((_, _) => Json("{\"error\":\"quota\"}", HttpStatusCode.TooManyRequests));
        var result = new OsvClient(handler).Audit(Three);
        var error = Assert.Single(result.Errors);
        Assert.Contains("429", error);
        Assert.Contains("quota", error);
        Assert.False(result.Complete);
    }

    [Fact]
    public void NetworkFailureIsReported()
    {
        var handler = new Fake((_, _) => throw new HttpRequestException("name resolution failed"));
        var result = new OsvClient(handler).Audit(Three);
        Assert.Contains("name resolution failed", Assert.Single(result.Errors));
        Assert.False(result.Complete);
    }

    [Fact]
    public void ADetailFailureStillReportsTheIdentifier()
    {
        var handler = new Fake((request, body) => request.RequestUri!.AbsolutePath.EndsWith("/v1/querybatch", StringComparison.Ordinal)
            ? Route(request, body)
            : Json("oops", HttpStatusCode.InternalServerError));
        var result = new OsvClient(handler).Audit(Three);
        Assert.Contains("GHSA-1", result.Vulnerable.SelectMany(f => f.Vulnerabilities).Select(v => v.Id));
        Assert.NotEmpty(result.Errors);
        Assert.All(result.Vulnerable.SelectMany(f => f.Vulnerabilities), v => Assert.Null(v.Summary));
    }

    [Fact]
    public void NoDependenciesMakesNoRequests()
    {
        var handler = new Fake(Route);
        var result = new OsvClient(handler).Audit([]);
        Assert.Empty(handler.Calls);
        Assert.True(result.Complete);
    }
}
