using System.Text;
using System.Text.RegularExpressions;
using DevTools.Core.Model;

namespace DevTools.Providers;

public sealed record MiseExportResult(string Text, IReadOnlyList<string> Skipped);

/// <summary>
/// Writes one project's tool versions as a <c>mise.toml</c>. Tool names are the mise registry's own short names
/// (each confirmed to exist). Only a plain dotted version is written, because mise needs a version and not a
/// range; everything else is listed as not exported rather than rounded to something the project never declared.
/// Advisory requirements (CI, engines fields) are not the project's own declaration and are never exported.
/// </summary>
public static partial class MiseExport
{
    private static readonly Dictionary<ToolKind, string> Names = new()
    {
        [ToolKind.Node] = "node",
        [ToolKind.Python] = "python",
        [ToolKind.Go] = "go",
        [ToolKind.Rustc] = "rust",
        [ToolKind.Ruby] = "ruby",
        [ToolKind.Php] = "php",
        [ToolKind.Deno] = "deno",
        [ToolKind.Bun] = "bun",
        [ToolKind.Gradle] = "gradle",
        [ToolKind.Maven] = "maven",
        [ToolKind.DotNetSdk] = "dotnet",
        [ToolKind.Zig] = "zig",
        [ToolKind.Terraform] = "terraform",
        [ToolKind.Kotlin] = "kotlin",
        [ToolKind.Scala] = "scala",
        [ToolKind.Elixir] = "elixir",
        [ToolKind.Julia] = "julia",
        [ToolKind.Cmake] = "cmake",
        [ToolKind.Uv] = "uv",
        [ToolKind.Pnpm] = "pnpm",
        [ToolKind.Yarn] = "yarn",
        [ToolKind.Bazel] = "bazel",
        [ToolKind.Sbt] = "sbt",
        [ToolKind.Leiningen] = "leiningen",
        [ToolKind.Conan] = "conan",
        [ToolKind.Meson] = "meson"
    };

    [GeneratedRegex(@"^[0-9]+(\.[0-9]+)*$", RegexOptions.CultureInvariant)]
    private static partial Regex PlainVersion();

    public static MiseExportResult Build(ProjectRecord project)
    {
        var entries = new List<string>();
        var skipped = new List<string>();

        var strongest = project.Requirements
            .Where(r => r.Strength <= RequirementStrength.Declared)
            .GroupBy(r => r.Tool)
            .Select(group => group.OrderBy(r => r.Precedence).ThenBy(r => r.Strength).First())
            .OrderBy(r => (int)r.Tool);

        foreach (var requirement in strongest)
        {
            var label = ToolKinds.Display(requirement.Tool) + " " + requirement.Raw;
            if (requirement.Tool == ToolKind.Jdk)
                skipped.Add(label + " (choose a java distribution)");
            else if (!Names.TryGetValue(requirement.Tool, out var name))
                skipped.Add(label + " (no mise registry entry)");
            else if (!PlainVersion().IsMatch(requirement.Raw))
                skipped.Add(label + " (not a plain version; mise needs one)");
            else
                entries.Add($"{name} = \"{requirement.Raw}\"");
        }

        var text = new StringBuilder();
        text.AppendLine("# generated by devtools-manager from " + (project.DisplayName));
        if (entries.Count > 0)
        {
            text.AppendLine("[tools]");
            foreach (var entry in entries) text.AppendLine(entry);
        }
        else if (skipped.Count == 0)
        {
            text.AppendLine("# nothing to export: this project declares no tool versions");
        }

        if (skipped.Count > 0)
        {
            text.AppendLine();
            text.AppendLine("# not exported:");
            foreach (var line in skipped) text.AppendLine("#   " + line);
        }

        return new MiseExportResult(text.ToString(), skipped);
    }
}
